const escape = text => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const table = new Map(pairs);
// Longest fragments first, so a sentence wins over a word it contains.
const pattern = new RegExp([...table.keys()].sort((a, b) => b.length - a.length).map(escape).join('|'), 'g');

export function renderKk(html) {
  return html.replace(pattern, match => table.get(match));
}
